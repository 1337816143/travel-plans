const moduleById = new Map(QINGDAO_PHASE4_MODULES.map((entry) => [entry.id, entry]));

interface PresetSeed {
  readonly id: string;
  readonly name: string;
  readonly description: string;
  readonly days: readonly (readonly string[])[];
  readonly mustPlaceIds: readonly string[];
  readonly tags: readonly string[];
  readonly originalV2EightDay?: boolean;
}

function preset(input: PresetSeed): PresetPlan {
  const moduleIds = [...new Set(input.days.flat())];
  const placeIds = [
    ...new Set(
      moduleIds.flatMap((moduleId) => {
        const module = moduleById.get(moduleId);
        if (!module) throw new Error(`未知的青岛日程模块：${moduleId}`);
        return module.placeIds;
      }),
    ),
  ];
  const must = new Set(input.mustPlaceIds);
  const selectionPriorities = Object.fromEntries(
    placeIds.map((placeId) => [placeId, must.has(placeId) ? 'must' : 'want']),
  ) as Record<string, PlacePriority>;
  return PresetPlanSchema.parse({
    schemaVersion: 1,
    createdAt: NOW,
    updatedAt: NOW,
    id: input.id,
    name: input.name,
    description: input.description,
    reviewStatus: 'review-required',
    totalDays: input.days.length,
    moduleIds,
    dayAssignments: input.days.map((moduleIdsForDay, index) => ({
      dayNumber: index + 1,
      moduleIds: [...moduleIdsForDay],
      notes: '可自由增删、跨日拖动、锁定并重新计算。',
    })),
    selectionPriorities,
    tags: [...input.tags],
    originalV2EightDay: input.originalV2EightDay ?? false,
    editable: true,
    sourceRefIds: ['legacy-v2.5.4-import-review-required'],
  });
}

